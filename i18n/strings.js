/* langue de l'interface : celle du cours actif */
let LANGUE = 'fr';
function definirLangue(l){ if(I18N[l]) LANGUE = l; }
function T(cle, valeurs){
  const table = I18N[LANGUE] || I18N.fr;
  let s = table[cle];
  if(s === undefined) s = (I18N.fr[cle] !== undefined) ? I18N.fr[cle] : cle;
  if(valeurs) for(const k in valeurs) s = s.split('{'+k+'}').join(valeurs[k]);
  return s;
}
